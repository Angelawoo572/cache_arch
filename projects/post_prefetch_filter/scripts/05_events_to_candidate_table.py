#!/usr/bin/env python3
"""Convert SPP event log into one-row-per-candidate training table.

Input: CSV produced by 04_patch_spp_candidate_logger.sh, with event rows:
  CAND,...  candidate generated by SPP
  USE,...   later demand access marked useful_prefetch by ChampSim

Output: CSV schema expected by rl_filter_story_starter.ipynb:
  trace,cycle,ip,addr,pf_addr,delta,spp_confidence,cache_hit,
  mshr_occupancy,mshr_size,pq_occupancy,pq_size,
  recent_spp_accuracy,recent_pc_accuracy,recent_delta_accuracy,
  bandwidth_bucket,set_pressure,
  outcome_useful,outcome_late,outcome_evicted_unused,outcome_duplicate

Important limitations of this first converter:
- cycle is event order, because the current event logger does not yet record CPU cycle.
- outcome_late and outcome_evicted_unused are set to 0 for now.
- PQ occupancy is whatever the logger wrote; current logger writes 0 because internal_PQ is private.
- outcome_useful is assigned by matching candidate pf_addr to later USE addr.
"""

import argparse
from collections import defaultdict, deque
from pathlib import Path

import pandas as pd

OUT_COLUMNS = [
    "trace",
    "cycle",
    "ip",
    "addr",
    "pf_addr",
    "delta",
    "spp_confidence",
    "cache_hit",
    "mshr_occupancy",
    "mshr_size",
    "pq_occupancy",
    "pq_size",
    "recent_spp_accuracy",
    "recent_pc_accuracy",
    "recent_delta_accuracy",
    "bandwidth_bucket",
    "set_pressure",
    "outcome_useful",
    "outcome_late",
    "outcome_evicted_unused",
    "outcome_duplicate",
]


def safe_int(x, default=0):
    try:
        return int(x)
    except Exception:
        return default


def load_events(path):
    df = pd.read_csv(path)
    df["event_idx"] = range(len(df))
    for col in [
        "cand_id",
        "addr",
        "ip",
        "pf_addr",
        "delta",
        "confidence",
        "fill_l2",
        "cache_hit",
        "mshr_occupancy",
        "mshr_size",
        "pq_occupancy",
        "pq_size",
        "useful_prefetch",
        "depth",
    ]:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce").fillna(0).astype("int64")
    return df


def assign_useful_labels(events):
    """Match each USE address to the oldest earlier unmatched CAND with same pf_addr."""
    cands = events[events["event"] == "CAND"].copy().reset_index(drop=True)
    uses = events[events["event"] == "USE"].copy()

    cands["outcome_useful"] = 0
    cands["use_event_idx"] = -1

    waiting = defaultdict(deque)
    for i, row in cands.iterrows():
        waiting[int(row["pf_addr"])].append(i)

    # Replay full event stream so USE only matches a candidate seen earlier.
    seen_waiting = defaultdict(deque)
    cand_global_to_local = {}
    for i, row in cands.iterrows():
        cand_global_to_local[int(row["event_idx"])] = i

    for _, row in events.iterrows():
        ev = row["event"]
        if ev == "CAND":
            local_i = cand_global_to_local.get(int(row["event_idx"]))
            if local_i is not None:
                seen_waiting[int(row["pf_addr"])].append(local_i)
        elif ev == "USE":
            addr = int(row["addr"])
            if seen_waiting[addr]:
                local_i = seen_waiting[addr].popleft()
                if cands.at[local_i, "outcome_useful"] == 0:
                    cands.at[local_i, "outcome_useful"] = 1
                    cands.at[local_i, "use_event_idx"] = int(row["event_idx"])

    return cands


def add_online_recent_accuracy(cands):
    """Add prior-only recent accuracy features in event order."""
    cands = cands.sort_values("event_idx").reset_index(drop=True)

    global_seen = 0
    global_useful = 0
    pc_seen = defaultdict(int)
    pc_useful = defaultdict(int)
    delta_seen = defaultdict(int)
    delta_useful = defaultdict(int)

    recent_global = []
    recent_pc = []
    recent_delta = []

    for _, row in cands.iterrows():
        ip = int(row["ip"])
        delta = int(row["delta"])

        recent_global.append(global_useful / global_seen if global_seen else 0.5)
        recent_pc.append(pc_useful[ip] / pc_seen[ip] if pc_seen[ip] else 0.5)
        recent_delta.append(delta_useful[delta] / delta_seen[delta] if delta_seen[delta] else 0.5)

        y = int(row["outcome_useful"])
        global_seen += 1
        global_useful += y
        pc_seen[ip] += 1
        pc_useful[ip] += y
        delta_seen[delta] += 1
        delta_useful[delta] += y

    cands["recent_spp_accuracy"] = recent_global
    cands["recent_pc_accuracy"] = recent_pc
    cands["recent_delta_accuracy"] = recent_delta
    return cands


def build_candidate_table(events, trace):
    cands = assign_useful_labels(events)
    cands = add_online_recent_accuracy(cands)

    # outcome_duplicate: repeated pf_addr candidates before a use can be suspicious.
    cands["outcome_duplicate"] = cands.duplicated(subset=["pf_addr"], keep="first").astype(int)

    out = pd.DataFrame()
    out["trace"] = trace
    out["cycle"] = cands["event_idx"]
    out["ip"] = cands["ip"]
    out["addr"] = cands["addr"]
    out["pf_addr"] = cands["pf_addr"]
    out["delta"] = cands["delta"]
    out["spp_confidence"] = cands["confidence"]
    out["cache_hit"] = cands["cache_hit"]
    out["mshr_occupancy"] = cands["mshr_occupancy"]
    out["mshr_size"] = cands["mshr_size"]
    out["pq_occupancy"] = cands["pq_occupancy"]
    out["pq_size"] = cands["pq_size"]
    out["recent_spp_accuracy"] = cands["recent_spp_accuracy"]
    out["recent_pc_accuracy"] = cands["recent_pc_accuracy"]
    out["recent_delta_accuracy"] = cands["recent_delta_accuracy"]

    # Not logged yet. Keep placeholders so notebook schema is stable.
    out["bandwidth_bucket"] = 0
    out["set_pressure"] = 0
    out["outcome_useful"] = cands["outcome_useful"].astype(int)
    out["outcome_late"] = 0
    out["outcome_evicted_unused"] = 0
    out["outcome_duplicate"] = cands["outcome_duplicate"].astype(int)

    return out[OUT_COLUMNS]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--events", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--trace", default="unknown")
    args = ap.parse_args()

    events = load_events(args.events)
    table = build_candidate_table(events, args.trace)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    table.to_csv(args.out, index=False)

    useful = int(table["outcome_useful"].sum())
    total = len(table)
    acc = useful / total if total else 0.0
    print("[events]", args.events)
    print("[out]", args.out)
    print("[candidates]", total)
    print("[useful]", useful)
    print("[candidate accuracy]", "{:.6f}".format(acc))
    print("[mshr avg]", "{:.3f}".format(table["mshr_occupancy"].mean() if total else 0.0))
    print("[mshr max]", int(table["mshr_occupancy"].max() if total else 0))


if __name__ == "__main__":
    main()
