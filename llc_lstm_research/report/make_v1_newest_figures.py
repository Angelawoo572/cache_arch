#!/usr/bin/env python3
"""Generate annotated V1 versus Newest report figures from the recorded replays."""

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'lstm' / 'v5_results' / 'v1_comparison'
REGIONS = (90, 110, 410, 430, 450)
MODELS = {'v1': ('V1', 'amber', 'sand'), 'newest': ('Newest', 'teal', 'tint')}
QUALITY = (
    ('prefetch_issued', 1, ',.0f'), ('direct_matches', 1, ',.0f'), ('timely_matches', 1, ',.0f'),
    ('accuracy', 100, '.2f'), ('timeliness', 100, '.2f'), ('coverage', 100, '.3f'),
    ('timely_coverage', 100, '.3f'),
)
CACHE = (
    ('llc_hit_rate', 100, '.2f'), ('llc_miss_rate', 100, '.2f'), ('llc_mpki', 1, '.3f'),
    ('aggregate_ipc', 1, '.6f'), ('roi_seconds', 1000, '.4f'), ('dram_total_bytes', 1e-6, '.3f'),
)


def read_rows(path):
    with path.open(newline='') as stream:
        return list(csv.DictReader(stream))


def cells(rows, fields):
    result = []
    for row_id, row in enumerate(rows):
        shade = MODELS[row['model']][2]
        for column, (field, factor, spec) in enumerate(fields):
            value = format(float(row[field]) * factor, spec) if row[field] else '—'
            result.append(f'{column}/{row_id}/{{{value}}}/{shade}')
    return ','.join(result)


def coverage_bars(rows, pooled, condition, regions, cohort):
    pairs = [(f'{region}M', [rows[condition, region, model] for model in MODELS])
             for region in regions]
    pairs.append(('Pooled', [pooled[condition, cohort, model] for model in MODELS]))
    return ','.join(f'{label}/{i}/{100 * float(v1["coverage"]):.3f}/{100 * float(newest["coverage"]):.3f}'
                    for i, (label, (v1, newest)) in enumerate(pairs))


def main():
    per_region = read_rows(DATA / 'per_region.csv')
    rows = {(row['condition'], int(row['region_m']), row['model']): row for row in per_region}
    pooled = {(row['condition'], row['cohort'], row['model']): row for row in read_rows(DATA / 'pooled.csv')}
    expected = {(condition, region, model)
                for condition in ('native', 'cap1000', 'cap150') for region in REGIONS for model in MODELS}
    if len(rows) != len(per_region) or rows.keys() != expected:
        raise ValueError('expected a single replay for each condition, region, and model')

    table_order = [(region, model) for region in REGIONS for model in MODELS]
    table_labels = [(f'{region}M', model) for region, model in table_order]
    table_labels.extend(('Pooled', model) for model in MODELS)
    macros = {'ComparisonRows': ','.join(f'{i}/{label} {MODELS[model][0]}/{MODELS[model][1]}'
                                         for i, (label, model) in enumerate(table_labels))}
    for condition, prefix in (('cap1000', 'Cap'), ('native', 'Native'), ('cap150', 'Small')):
        ordered = [rows[condition, region, model] for region, model in table_order]
        ordered.extend(pooled[condition, 'all_regions', model] for model in MODELS)
        macros[f'{prefix}Quality'] = cells(ordered, QUALITY)
        macros[f'{prefix}Cache'] = cells(ordered, CACHE)
    for region, name in ((90, 'Ninety'), (110, 'OneTen')):
        counts = [int(rows['cap1000', region, model]['direct_matches']) for model in MODELS]
        macros[f'Cap{name}Covered'] = f'{counts[0]:,} $\\to$ {counts[1]:,}'
    macros['CapEqualVOneCoverageBars'] = coverage_bars(rows, pooled, 'cap1000', REGIONS[:2], 'v1_test_regions')
    macros['NativeCoverageBars'] = coverage_bars(rows, pooled, 'native', REGIONS, 'all_regions')

    fresh = [[rows['cap150', region, model] for region in REGIONS[2:]] for model in MODELS]
    if any(int(rows['cap150', region, model]['prefetch_issued']) != 300
           for region in REGIONS for model in MODELS):
        raise ValueError('the small-budget result is not equal-volume')
    covered = [sum(int(row['direct_matches']) for row in cohort) for cohort in fresh]
    cycles = [sum(int(row['roi_cycles']) for row in cohort) for cohort in fresh]
    hard_region = [int(rows['cap150', 430, model]['direct_matches']) for model in MODELS]
    macros['SmallBudgetSummary'] = (
        f'五段上两版每段都实际发了 300 个请求。在 410M/430M/450M 合计，'
        f'覆盖的 NoPF miss 从 {covered[0]:,} 到 {covered[1]:,} 个，'
        f'完成时间变化 {100 * (cycles[1] / cycles[0] - 1):+.3f}\\%。'
        f'430M 本身从 {hard_region[0]} 到 {hard_region[1]}，说明紧预算下的收益会因区间变化。'
    )
    target = ROOT / 'report' / 'v1_newest_data.tex'
    target.write_text('% Generated by make_v1_newest_figures.py from per_region.csv and pooled.csv.\n'
                      + ''.join(f'\\newcommand{{\\{name}}}{{{value}}}\n' for name, value in macros.items()))


if __name__ == '__main__':
    main()
