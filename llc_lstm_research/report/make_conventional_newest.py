#!/usr/bin/env python3
"""Format the frozen 32-cycle NoPF-model conventional comparison for LaTeX."""

import csv
from pathlib import Path


REPORT = Path(__file__).resolve().parent
DATA = REPORT.parent / 'lstm' / 'v5_results' / 'clean32'
REGIONS = (410, 430, 450)
POLICIES = {
    'nopf': 'NoPF',
    'next_line': 'Next-Line',
    'stride': 'Stride',
    'streamer': 'Streamer',
    'ampm': 'AMPM',
    'spp': 'SPP',
    'lstm': 'Newest',
}

# Column order also controls the pooled plots.
METRICS = (
    ('IPC', 'ipc', 1, 5),
    ('Time (ms)', 'time_ms', 1, 3),
    ('Accuracy', 'accuracy', 100, 2),
    ('Timeliness', 'timeliness', 100, 2),
    ('Coverage', 'direct_coverage', 100, 2),
    ('Timely cov.', 'timely_coverage', 100, 2),
    ('LLC hit', 'llc_hit_rate', 100, 2),
    ('LLC miss', 'llc_miss_rate', 100, 2),
    ('MPKI', 'llc_mpki', 1, 3),
    ('DRAM (MB)', 'dram_bytes', 1 / 1_000_000, 3),
)
PHASE_KEYS = {
    'ipc': ('aggregate_ipc', 1),
    'time_ms': ('roi_seconds', 1_000),
    'direct_coverage': ('coverage', 1),
    'dram_bytes': ('dram_total_bytes', 1),
}


def rows(filename):
    with (DATA / filename).open(newline='') as stream:
        return [
            row for row in csv.DictReader(stream)
            if row['label_latency'] == '32' and row['group'] == 'fresh'
            and row['policy'] in POLICIES
        ]


def numeric(row, key, multiplier, by_phase=False):
    if by_phase:
        key, conversion = PHASE_KEYS.get(key, (key, 1))
        multiplier *= conversion
    value = row[key]
    return multiplier * float(value) if value else None


def display(value, digits):
    return '—' if value is None else f'{value:,.{digits}f}'


def metric_cells(row, by_phase=False):
    fields = [display(numeric(row, key, factor, by_phase), digits)
              for _, key, factor, digits in METRICS]
    fields.append(f'{int(row["prefetch_issued" if by_phase else "accepted"]):,}')
    return fields


def table_line(fields):
    return ' & '.join(fields) + ' \\\\'


def tex_command(name, lines):
    return f'\\newcommand{{\\{name}}}{{%\n' + '%\n'.join(lines) + '%\n}\n'


def main():
    phase = {(int(row['region']), row['policy']): row for row in rows('per_phase.csv')}
    pooled = {row['policy']: row for row in rows('pooled.csv')}
    if set(phase) != {(region, policy) for region in REGIONS for policy in POLICIES} or set(pooled) != POLICIES.keys():
        raise ValueError('incomplete conventional comparison')

    chart_labels = [f'{index}/{{{label}}}/{"teal" if key == "lstm" else "muted"}'
                    for index, (key, label) in enumerate(POLICIES.items())]
    region_headers = [f'{index}/{{{region}M}}' for index, region in enumerate(REGIONS)]
    ipc_bars = [
        f'{col}/{index}/{float(phase[region,policy]["aggregate_ipc"]):.8f}/'
        f'{float(phase[region,policy]["aggregate_ipc"]):.5f}/{"teal" if policy == "lstm" else "muted!62"}'
        for col, region in enumerate(REGIONS) for index, policy in enumerate(POLICIES)
    ]
    phase_table = []
    for region in REGIONS:
        denominator = int(phase[region, 'nopf']['nopf_misses'])
        phase_table.append(r'\addlinespace[2pt]'
                           rf'\multicolumn{{12}}{{@{{}}l}}{{\textbf{{{region}M}} \quad '
                           rf'NoPF misses {denominator:,}}} \\')
        for policy, title in POLICIES.items():
            phase_table.append(table_line([fr'\textbf{{{title}}}' if policy == 'lstm' else title]
                                          + metric_cells(phase[region, policy], True)))

    plots = [[], []]
    plots_headers = [[], []]
    for column, (title, key, factor, digits) in enumerate(METRICS):
        group, slot = divmod(column, 5)
        values = [numeric(pooled[policy], key, factor) for policy in POLICIES]
        maximum = 100 if factor == 100 else max(value for value in values if value is not None)
        axis_title = title + (r' \%' if factor == 100 else '')
        plots_headers[group].append(f'{slot}/{{{axis_title}}}')
        for index, (policy, value) in enumerate(zip(POLICIES, values)):
            fraction = max(0, value or 0) / maximum
            tone = 'teal' if policy == 'lstm' else 'muted!62'
            plots[group].append(f'{slot}/{index}/{fraction:.8f}/{{{display(value, digits)}}}/{tone}')

    pooled_table = [table_line([fr'\textbf{{{title}}}' if policy == 'lstm' else title]
                               + metric_cells(pooled[policy])) for policy, title in POLICIES.items()]
    text = '% Generated by make_conventional_newest.py from the clean32 CSV files.\n'
    for name, lines in (
        ('ConvChartLabels', [','.join(chart_labels)]),
        ('ConvRegionHeaders', [','.join(region_headers)]),
        ('ConvIpcBars', [','.join(ipc_bars)]),
        ('ConvPhaseTable', phase_table),
        ('ConvPooledHeadA', [','.join(plots_headers[0])]),
        ('ConvPooledHeadB', [','.join(plots_headers[1])]),
        ('ConvPooledBarsA', [','.join(plots[0])]),
        ('ConvPooledBarsB', [','.join(plots[1])]),
        ('ConvPooledTable', pooled_table),
    ):
        text += tex_command(name, lines)
    (REPORT / 'conventional_newest_data.tex').write_text(text)


if __name__ == '__main__':
    main()
